import { cleanup, render, screen, waitFor } from "@solidjs/testing-library";
import { userEvent } from "@testing-library/user-event";
import type { BlueprintGraphProjection, BlueprintPin } from "@ue-shed/protocol";
import { EffectRuntimeProvider } from "@ue-shed/ui";
import { Effect, Layer, ManagedRuntime } from "effect";
import { afterAll, afterEach, describe, expect, it, vi } from "vitest";
import { BlueprintGraphViewer } from "./blueprint-graph-viewer.js";

const runtime = ManagedRuntime.make(Layer.empty);

afterEach(cleanup);
afterAll(() => runtime.dispose());

function pin(id: string, name: string, direction: "input" | "output"): BlueprintPin {
	return {
		id,
		name,
		source_index: 0,
		tooltip: "",
		direction,
		pin_type: {
			category: "exec",
			subcategory: "",
			container_type: "none",
			is_reference: false,
			is_weak_pointer: false,
			member_reference: { name: "" },
			is_const: false,
			is_uobject_wrapper: false,
			serialize_as_single_precision_float: false
		},
		default_value: "",
		autogenerated_default_value: "",
		linked_to: [],
		sub_pins: [],
		flags: 0
	};
}

const blueprint: BlueprintGraphProjection = {
	schema_version: 1,
	object_path: "/Game/UI/WBP_Settings.WBP_Settings",
	coverage_gaps: [],
	graphs: [
		{
			object_path: "/Game/UI/WBP_Settings.WBP_Settings:EventGraph",
			name: "EventGraph",
			nodes: [
				{
					object_path: "/Game/UI/WBP_Settings.WBP_Settings:EventGraph.Event",
					class_path: "/Script/BlueprintGraph.K2Node_Event",
					kind: "event",
					title: "On Clicked",
					position: { x: 0, y: 0 },
					properties: [],
					pins: [pin("event-out", "then", "output")],
					subclass_tail_bytes: 0
				},
				{
					object_path: "/Game/UI/WBP_Settings.WBP_Settings:EventGraph.Call",
					class_path: "/Script/BlueprintGraph.K2Node_CallFunction",
					kind: "function_call",
					title: "Apply Settings",
					position: { x: 360, y: 0 },
					properties: [],
					pins: [pin("call-in", "execute", "input")],
					subclass_tail_bytes: 0
				}
			],
			links: [
				{
					from: {
						node_object_path: "/Game/UI/WBP_Settings.WBP_Settings:EventGraph.Event",
						pin_id: "event-out"
					},
					to: {
						node_object_path: "/Game/UI/WBP_Settings.WBP_Settings:EventGraph.Call",
						pin_id: "call-in"
					}
				}
			]
		}
	]
};

describe("BlueprintGraphViewer", () => {
	it("opens a saved package and renders its graph topology", async () => {
		const readBlueprint = vi.fn((assetPath: string) =>
			Effect.succeed({ assetPath, blueprint, status: "ready" as const })
		);
		const view = render(() => (
			<EffectRuntimeProvider runtime={runtime}>
				<BlueprintGraphViewer
					client={{
						chooseBlueprint: () => Effect.succeed({ status: "cancelled" as const }),
						readBlueprint
					}}
				/>
			</EffectRuntimeProvider>
		));

		const path = "C:/Project/Content/UI/WBP_Settings.uasset";
		await userEvent.setup().type(screen.getByLabelText("Blueprint package path"), path);
		await userEvent.setup().click(screen.getByRole("button", { name: "Open graph" }));

		await waitFor(() => expect(readBlueprint).toHaveBeenCalledWith(path));
		expect(await screen.findByText("Topology complete")).toBeDefined();
		expect(screen.getByRole("button", { name: "Inspect On Clicked" })).toBeDefined();
		expect(screen.getByRole("button", { name: "Inspect Apply Settings" })).toBeDefined();
		expect(view.container.querySelectorAll("svg path")).toHaveLength(1);

		await userEvent
			.setup()
			.click(screen.getByRole("button", { name: "Inspect Apply Settings" }));
		expect(screen.getByText("/Script/BlueprintGraph.K2Node_CallFunction")).toBeDefined();
	});

	it("keeps native-reader failures actionable", async () => {
		render(() => (
			<EffectRuntimeProvider runtime={runtime}>
				<BlueprintGraphViewer
					client={{
						chooseBlueprint: () =>
							Effect.succeed({
								assetPath: "C:/Project/Content/BP_Bad.uasset",
								message: "Blueprint node payload ended early.",
								recovery: "Open an uncooked UE 5.7 package.",
								status: "failed" as const
							}),
						readBlueprint: () => Effect.succeed({ status: "cancelled" as const })
					}}
				/>
			</EffectRuntimeProvider>
		));

		await userEvent.setup().click(screen.getByRole("button", { name: "Browse…" }));
		const alert = await screen.findByRole("alert");
		expect(alert.textContent).toContain("ended early");
		expect(alert.textContent).toContain("uncooked UE 5.7");
	});
});
