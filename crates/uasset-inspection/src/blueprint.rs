//! Compact, evaluator-independent projection of saved Blueprint editor graphs.
//!
//! The projection joins `UEdGraph::Nodes` with the native `UEdGraphNode` pin stream. It is enough
//! to lay out and inspect the saved graph, but deliberately does not claim Blueprint compilation
//! or execution semantics.

use std::collections::{HashMap, HashSet};

use serde::{Deserialize, Serialize};
use uasset_parser::asset::{
    DecodedAsset, DecodedBlueprintGraphNode, DecodedUObject, ED_GRAPH_CLASS,
    EdGraphMemberReference, EdGraphPin, EdGraphPinContainerType, EdGraphPinDirection,
    EdGraphPinReference, EdGraphPinType, EdGraphTerminalType,
};
use uasset_parser::package::{Package, PackageIndex};
use uasset_parser::property::{PropertyStream, PropertyValue, RawReason, TextHistory, TextValue};

use crate::generic::{PropertyOutput, property_outputs};

pub const BLUEPRINT_GRAPH_SCHEMA_VERSION: u8 = 1;
const CONTROL_RIG_BLUEPRINT_CLASS: &str = "/Script/ControlRigDeveloper.ControlRigBlueprint";

