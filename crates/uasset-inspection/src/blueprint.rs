fn project_member_reference(
    package: &Package,
    reference: &EdGraphMemberReference,
) -> BlueprintMemberReference {
    BlueprintMemberReference {
        parent: resolve_object(package, reference.parent),
        name: resolve_name(package, reference.name),
        guid: (!reference.guid.is_zero()).then(|| reference.guid.to_string()),
    }
}

fn pin_reference(package: &Package, reference: &EdGraphPinReference) -> BlueprintPinReference {
    BlueprintPinReference {
        node_object_path: resolve_object(package, reference.owning_node),
        pin_id: reference.pin_id.to_string(),
    }
}

fn normalize_link(
    first: BlueprintPinReference,
    second: BlueprintPinReference,
    directions: &HashMap<BlueprintPinReference, BlueprintPinDirection>,
) -> BlueprintLink {
    match (directions.get(&first), directions.get(&second)) {
        (Some(BlueprintPinDirection::Output), Some(BlueprintPinDirection::Input)) => {
            BlueprintLink {
                from: first,
                to: second,
            }
        }
        (Some(BlueprintPinDirection::Input), Some(BlueprintPinDirection::Output)) => {
            BlueprintLink {
                from: second,
                to: first,
            }
        }
        _ if first <= second => BlueprintLink {
            from: first,
            to: second,
        },
        _ => BlueprintLink {
            from: second,
            to: first,
        },
    }
}

fn pin_directions(
    nodes: &[&DecodedBlueprintGraphNode],
) -> HashMap<BlueprintPinReference, BlueprintPinDirection> {
    nodes
        .iter()
        .flat_map(|node| {
            node.pins.iter().flatten().map(|pin| {
                (
                    BlueprintPinReference {
                        node_object_path: Some(node.object_path.to_string()),
                        pin_id: pin.id.to_string(),
                    },
                    match pin.direction {
                        EdGraphPinDirection::Input => BlueprintPinDirection::Input,
                        EdGraphPinDirection::Output => BlueprintPinDirection::Output,
                    },
                )
            })
        })
        .collect()
}

fn node_kind(class_path: &str) -> BlueprintNodeKind {
    match class_path.rsplit('.').next() {
        Some("K2Node_Event" | "K2Node_CustomEvent") => BlueprintNodeKind::Event,
        Some("K2Node_CallFunction") => BlueprintNodeKind::FunctionCall,
        Some("K2Node_VariableGet") => BlueprintNodeKind::VariableGet,
        Some("K2Node_VariableSet") => BlueprintNodeKind::VariableSet,
        _ => BlueprintNodeKind::Other,
    }
}

fn node_title(package: &Package, node: &DecodedBlueprintGraphNode) -> String {
    ["EventReference", "FunctionReference", "VariableReference"]
        .iter()
        .find_map(|property_name| {
            let PropertyValue::Struct(reference) =
                property(package, &node.properties, property_name)?
            else {
                return None;
            };
            let PropertyValue::Name(member_name) = property(package, reference, "MemberName")?
            else {
                return None;
            };
            package.resolve_name(*member_name)
        })
        .or_else(|| {
            node.class_path
                .as_str()
                .rsplit('.')
                .next()
                .map(str::to_owned)
        })
        .unwrap_or_else(|| node.object_path.to_string())
}

fn node_references(package: &Package, properties: &PropertyStream) -> Vec<PackageIndex> {
    let Some(PropertyValue::Array(values)) = property(package, properties, "Nodes") else {
        return Vec::new();
    };
    values
        .iter()
        .filter_map(|value| match value {
            PropertyValue::ObjectRef(index) => Some(*index),
            _ => None,
        })
        .collect()
}

fn property<'a>(
    package: &Package,
    stream: &'a PropertyStream,
    property_name: &str,
) -> Option<&'a PropertyValue> {
    stream.records.iter().find_map(|record| {
        (package.resolve_name_str(record.name) == Some(property_name)).then_some(&record.value)
    })
}

fn integer_property(
    package: &Package,
    properties: &PropertyStream,
    property_name: &str,
) -> Option<i64> {
    match property(package, properties, property_name)? {
        PropertyValue::Int(value) => Some(*value),
        PropertyValue::UInt(value) => i64::try_from(*value).ok(),
        _ => None,
    }
}

fn guid_property(
    package: &Package,
    properties: &PropertyStream,
    property_name: &str,
) -> Option<String> {
    let PropertyValue::Guid(value) = property(package, properties, property_name)? else {
        return None;
    };
    Some(value.to_string())
}

fn project_text(text: &TextValue) -> Option<BlueprintText> {
    if text.source.is_empty() {
        return None;
    }
    let (namespace, key) = match &text.history {
        TextHistory::None => (None, None),
        TextHistory::Base { namespace, key } => (
            Some(namespace.clone()),
            (!key.is_empty()).then(|| key.clone()),
        ),
        TextHistory::NamedFormat { format, .. } => text_identity_parts(format),
    };
    Some(BlueprintText {
        source: text.source.clone(),
        namespace,
        key,
    })
}

fn text_identity_parts(text: &TextValue) -> (Option<String>, Option<String>) {
    match &text.history {
        TextHistory::None => (None, None),
        TextHistory::Base { namespace, key } => (
            Some(namespace.clone()),
            (!key.is_empty()).then(|| key.clone()),
        ),
        TextHistory::NamedFormat { format, .. } => text_identity_parts(format),
    }
}

fn resolve_name(package: &Package, name: uasset_parser::archive::NameRef) -> String {
    package
        .resolve_name_cow(name)
        .map(|name| name.into_owned())
        .unwrap_or_else(|| "<unresolved>".to_owned())
}

fn resolve_object(package: &Package, index: PackageIndex) -> Option<String> {
    (index != PackageIndex::Null)
        .then(|| package.resolve_index_str(index).map(str::to_owned))
        .flatten()
}

fn blueprint_path(graph_path: &str) -> String {
    graph_path
        .rsplit_once('.')
        .map_or_else(|| graph_path.to_owned(), |(parent, _)| parent.to_owned())
}

fn direct_child_of(object_path: &str, graph_prefix: &str) -> bool {
    object_path
        .strip_prefix(graph_prefix)
        .is_some_and(|suffix| !suffix.contains('.'))
}

fn objects(assets: &[DecodedAsset]) -> impl Iterator<Item = &DecodedUObject> {
    assets.iter().filter_map(|asset| match asset {
        DecodedAsset::UObject(object) => Some(object),
        _ => None,
    })
}

fn blueprint_nodes(assets: &[DecodedAsset]) -> impl Iterator<Item = &DecodedBlueprintGraphNode> {
    assets.iter().filter_map(|asset| match asset {
        DecodedAsset::BlueprintGraphNode(node) => Some(node),
        _ => None,
    })
}

fn coverage_gap(
    gaps: &mut Vec<BlueprintGraphCoverageGap>,
    object_path: &str,
    reason: BlueprintGraphCoverageGapReason,
    detail: impl Into<String>,
) {
    gaps.push(BlueprintGraphCoverageGap {
        object_path: object_path.to_owned(),
        reason,
        detail: detail.into(),
    });
}

