    extra.nodes.truncate(1);
    extra.links.clear();
    for node in &mut extra.nodes {
        node.object_path = node.object_path.replace("EventGraph", "Knock");
    }
    after.graphs.push(extra);

    let diff = diff_blueprints(&before, &after);
    assert_eq!(diff.variables.len(), 3);
