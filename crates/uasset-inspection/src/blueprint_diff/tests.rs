const GRAPH: &str = "/Game/BP_Door.BP_Door:EventGraph";

fn pin_type(category: &str) -> BlueprintPinType {
    BlueprintPinType {
        category: category.to_owned(),
        subcategory: String::new(),
        subcategory_object: None,
        container_type: BlueprintPinContainerType::None,
        value_type: None,
        is_reference: false,
        is_weak_pointer: false,
        member_reference: BlueprintMemberReference {
            parent: None,
            name: String::new(),
            guid: None,
        },
        is_const: false,
        is_uobject_wrapper: false,
        serialize_as_single_precision_float: false,
    }
}

fn pin(id: &str, name: &str, direction: BlueprintPinDirection, category: &str) -> BlueprintPin {
    BlueprintPin {
        id: id.to_owned(),
        name: name.to_owned(),
        friendly_name: None,
        source_index: -1,
        tooltip: String::new(),
        direction,
        pin_type: pin_type(category),
        default_value: String::new(),
        autogenerated_default_value: String::new(),
        default_object: None,
        default_text_value: None,
        linked_to: Vec::new(),
        sub_pins: Vec::new(),
        parent_pin: None,
        reference_pass_through_connection: None,
        persistent_guid: None,
        flags: 0,
    }
}

fn exec_in(id: &str) -> BlueprintPin {
    pin(id, "execute", BlueprintPinDirection::Input, "exec")
}

fn exec_out(id: &str, name: &str) -> BlueprintPin {
    pin(id, name, BlueprintPinDirection::Output, "exec")
}

fn node(name: &str, guid: &str, title: &str, pins: Vec<BlueprintPin>) -> BlueprintNode {
    BlueprintNode {
        object_path: format!("{GRAPH}.{name}"),
        class_path: "/Script/BlueprintGraph.K2Node_CallFunction".to_owned(),
        kind: BlueprintNodeKind::FunctionCall,
        title: title.to_owned(),
        position: BlueprintNodePosition { x: 0, y: 0 },
        guid: Some(guid.to_owned()),
        properties: Vec::new(),
        pins,
        subclass_tail_bytes: 0,
    }
}

fn wire(from: (&str, &str), to: (&str, &str)) -> BlueprintLink {
    let end = |(node, pin): (&str, &str)| BlueprintPinReference {
        node_object_path: Some(format!("{GRAPH}.{node}")),
        pin_id: pin.to_owned(),
    };
    BlueprintLink {
        from: end(from),
        to: end(to),
    }
}

fn projection(nodes: Vec<BlueprintNode>, links: Vec<BlueprintLink>) -> BlueprintGraphProjection {
    BlueprintGraphProjection {
        schema_version: BLUEPRINT_GRAPH_SCHEMA_VERSION,
        object_path: "/Game/BP_Door.BP_Door".to_owned(),
        graphs: vec![BlueprintGraph {
            object_path: GRAPH.to_owned(),
            name: "EventGraph".to_owned(),
            guid: Some("GRAPH-GUID".to_owned()),
            nodes,
            links,
        }],
        definition: BlueprintDefinition {
            parent_class: Some("/Script/Engine.Actor".to_owned()),
            variables: Some(Vec::new()),
            default_object: None,
            construction_script: None,
        },
        coverage_gaps: Vec::new(),
    }
}

/// Begin Play → Open Door (Speed 3) → Play Sound.
fn door() -> BlueprintGraphProjection {
    let mut open = node(
        "K2Node_CallFunction_1",
        "G-OPEN",
        "OpenDoor",
        vec![
            exec_in("open-in"),
            exec_out("open-then", "then"),
            pin("open-speed", "Speed", BlueprintPinDirection::Input, "real"),
        ],
    );
    open.pins[2].default_value = "3".to_owned();
    projection(
        vec![
            node(
                "K2Node_Event_0",
                "G-BEGIN",
                "ReceiveBeginPlay",
                vec![exec_out("begin-then", "then")],
            ),
            open,
            node(
                "K2Node_CallFunction_2",
                "G-SOUND",
                "PlaySound",
                vec![exec_in("sound-in"), exec_out("sound-then", "then")],
            ),
        ],
        vec![
            wire(
                ("K2Node_Event_0", "begin-then"),
                ("K2Node_CallFunction_1", "open-in"),
            ),
            wire(
                ("K2Node_CallFunction_1", "open-then"),
                ("K2Node_CallFunction_2", "sound-in"),
            ),
        ],
    )
}

#[test]
fn the_same_blueprint_has_no_changes() {
    let diff = diff_blueprints(&door(), &door());
    assert!(diff.graphs.is_empty());
    assert_eq!(diff.counts.nodes_unchanged, 3);
    assert_eq!(diff.counts.graphs_unchanged, 1);
}

#[test]
fn moving_and_renumbering_nodes_is_counted_but_not_a_change() {
    let mut after = door();
    let graph = &mut after.graphs[0];
    for node in &mut graph.nodes {
        node.position = BlueprintNodePosition { x: 400, y: -96 };
        node.properties.push(PropertyOutput {
            name: "NodePosX".to_owned(),
            type_name: "IntProperty".to_owned(),
            value: PropertyValueOutput::Int { value: 400 },
        });
    }
    // A recompile renumbers the second call, and its wires follow it.
    let renumbered = format!("{GRAPH}.K2Node_CallFunction_7");
    let old = format!("{GRAPH}.K2Node_CallFunction_2");
    graph.nodes[2].object_path.clone_from(&renumbered);
    for link in &mut graph.links {
        for end in [&mut link.from, &mut link.to] {
            if end.node_object_path.as_deref() == Some(old.as_str()) {
                end.node_object_path = Some(renumbered.clone());
            }
        }
    }
    let diff = diff_blueprints(&door(), &after);
    assert!(diff.graphs.is_empty(), "{:#?}", diff.graphs);
    assert_eq!(diff.counts.nodes_moved, 3);
    assert_eq!(diff.counts.nodes_renumbered, 1);
    assert_eq!(diff.counts.nodes_unchanged, 3);
}

