#[test]
fn an_inserted_node_lists_its_wires_and_the_rewire() {
    // Begin Play → Open Door → Wait → Play Sound: Open Door's `then` moves to Wait.
    let mut after = door();
    let graph = &mut after.graphs[0];
    graph.nodes.push(node(
        "K2Node_CallFunction_3",
        "G-WAIT",
        "Delay",
        vec![exec_in("wait-in"), exec_out("wait-then", "Completed")],
    ));
    graph.links = vec![
        wire(
            ("K2Node_Event_0", "begin-then"),
            ("K2Node_CallFunction_1", "open-in"),
        ),
        wire(
            ("K2Node_CallFunction_1", "open-then"),
            ("K2Node_CallFunction_3", "wait-in"),
        ),
        wire(
            ("K2Node_CallFunction_3", "wait-then"),
            ("K2Node_CallFunction_2", "sound-in"),
        ),
    ];
    let diff = diff_blueprints(&door(), &after);
    let graph = &diff.graphs[0];
    assert_eq!(graph.nodes.len(), 1);
    let added = &graph.nodes[0];
    assert_eq!(added.status, BlueprintChangeStatus::Added);
    assert_eq!(added.node.title, "Delay");
    assert_eq!(
        added.wires,
        vec![
            BlueprintNodeWire {
                pin: "execute".to_owned(),
                other: BlueprintEndpoint {
                    node: "OpenDoor".to_owned(),
                    pin: "then".to_owned(),
                },
            },
            BlueprintNodeWire {
                pin: "Completed".to_owned(),
                other: BlueprintEndpoint {
                    node: "PlaySound".to_owned(),
                    pin: "execute".to_owned(),
                },
            },
        ]
    );
    // The wire from Open Door to Play Sound went away; the new ones are on Delay.
    assert_eq!(graph.wires.len(), 1);
    assert_eq!(graph.wires[0].status, BlueprintChangeStatus::Removed);
    assert_eq!(graph.wires[0].from.node, "OpenDoor");
    assert_eq!(graph.wires[0].to.node, "PlaySound");
    assert_eq!(diff.counts.nodes_added, 1);
    assert_eq!(diff.counts.wires_removed, 1);
}

#[test]
fn a_wire_moved_to_another_pin_is_rewired() {
    // Begin Play now runs Play Sound instead of Open Door.
    let mut after = door();
    after.graphs[0].links[0] = wire(
        ("K2Node_Event_0", "begin-then"),
        ("K2Node_CallFunction_2", "sound-in"),
    );
    let diff = diff_blueprints(&door(), &after);
    let wires = &diff.graphs[0].wires;
    assert_eq!(wires.len(), 1, "{wires:#?}");
    let rewired = &wires[0];
    assert_eq!(rewired.status, BlueprintChangeStatus::Changed);
    assert_eq!(rewired.from.node, "ReceiveBeginPlay");
    assert_eq!(rewired.to.node, "PlaySound");
    assert_eq!(
        rewired.previous,
        Some(BlueprintWireEnd {
            end: BlueprintWireSide::To,
            endpoint: BlueprintEndpoint {
                node: "OpenDoor".to_owned(),
                pin: "execute".to_owned(),
            },
        })
    );
    assert_eq!(diff.counts.wires_rewired, 1);
}

