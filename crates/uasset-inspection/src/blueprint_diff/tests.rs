    assert_eq!(diff.variables[2].status, BlueprintChangeStatus::Removed);
    assert_eq!(diff.graphs.len(), 1);
    assert_eq!(diff.graphs[0].status, BlueprintChangeStatus::Added);
    assert_eq!(diff.counts.graphs_added, 1);
    assert_eq!(diff.counts.nodes_added, 1);
