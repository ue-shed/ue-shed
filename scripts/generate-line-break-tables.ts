/**
 * Writes the native line-break word-count tables from the `linebreak` package that
 * `localizationWordCount` uses, so the Rust count reproduces it code point for code point:
 * every UAX #14 class the package assigns, its pair table, and the code points of the scripts
 * that need dictionary breaking. Run `node scripts/generate-line-break-tables.ts` after
 * upgrading `linebreak` or Node, then rerun the parity tests.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const requireFromGameText = createRequire(join(root, "packages/game-text/package.json"));
const linebreakEntry = requireFromGameText.resolve("linebreak");
const requireFromLinebreak = createRequire(linebreakEntry);
// SAFETY: unicode-trie exports the trie class linebreak itself constructs from its data.
// Verified by: line_break.rs vectors test — the tables match the package on every code point.
const UnicodeTrie = requireFromLinebreak("unicode-trie") as new (data: Uint8Array) => {
	get(codePoint: number): number;
};
// SAFETY: every npm package.json names its version.
// Verified by: line_break.rs vectors test — the tables match the package on every code point.
const linebreakVersion = (
	JSON.parse(readFileSync(join(dirname(linebreakEntry), "../package.json"), "utf8")) as {
		version: string;
	}
).version;
const bundle = readFileSync(join(dirname(linebreakEntry), "module.mjs"), "utf8");

const encoded = /toByteArray\("([A-Za-z0-9+/=]+)"\)/u.exec(bundle)?.[1];
if (encoded === undefined) throw new Error("The linebreak class trie was not found.");
const trie = new UnicodeTrie(new Uint8Array(Buffer.from(encoded, "base64")));

// The pair table's five break actions, named by the constants the bundle declares.
const actions = [
	...bundle.matchAll(/const (\$[\w$]+) = (\d); \/\/ (?:Direct|Indirect|Prohibited)/gu)
];
if (actions.length !== 5) throw new Error("The linebreak break actions were not found.");
const table = /export\$5bdb8ccbf5c57afc = (\[[\s\S]*?\n\]);/u.exec(bundle)?.[1];
if (table === undefined) throw new Error("The linebreak pair table was not found.");
let numeric = table.replace(/\/\/[^\n]*/gu, "");
for (const [, name, value] of actions) numeric = numeric.split(name!).join(value!);
// SAFETY: checked below to be 33 rows of 33 integers.
// Verified by: line_break.rs vectors test — the tables match the package on every code point.
const pairs = JSON.parse(numeric) as number[][];
if (
	pairs.length !== 33 ||
	pairs.some((row) => row.length !== 33 || row.some((value) => !Number.isInteger(value)))
)
	throw new Error("The linebreak pair table is not 33 by 33.");

const classes: [number, number][] = [];
for (let codePoint = 0; codePoint <= 0x10ffff; codePoint++) {
	const value = trie.get(codePoint);
	if (classes.at(-1)?.[1] !== value) classes.push([codePoint, value]);
}
const dictionary = /[\p{Script=Thai}\p{Script=Lao}\p{Script=Khmer}\p{Script=Myanmar}]/u;
const scripts: [number, number][] = [];
for (let codePoint = 0; codePoint <= 0x10ffff; codePoint++) {
	if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
	if (!dictionary.test(String.fromCodePoint(codePoint))) continue;
	const last = scripts.at(-1);
	if (last && last[1] === codePoint - 1) last[1] = codePoint;
	else scripts.push([codePoint, codePoint]);
}

const hex = (value: number) => `0x${value.toString(16)}`;
const lines = (values: string[], width = 8) => {
	const rows: string[] = [];
	for (let index = 0; index < values.length; index += width)
		rows.push(`    ${values.slice(index, index + width).join(" ")}`);
	return rows.join("\n");
};
const output = `//! Generated by scripts/generate-line-break-tables.ts from linebreak ${linebreakVersion}
//! (MIT, Devon Govett) and Node ${process.versions.node} (Unicode ${process.versions.unicode}).
//! Do not edit; regenerate it instead.

/// The first code point of each run that shares a UAX #14 class, in code point order.
pub(crate) static CLASS_STARTS: [u32; ${classes.length}] = [
${lines(classes.map(([start]) => `${hex(start)},`))}
];
/// The class of each run in \`CLASS_STARTS\`.
pub(crate) static CLASS_VALUES: [u8; ${classes.length}] = [
${lines(
	classes.map(([, value]) => `${value},`),
	24
)}
];
/// Break actions by current and next class: 0 direct, 1 indirect, 2 indirect for combining
/// marks, 3 prohibited for combining marks, 4 prohibited.
pub(crate) static PAIRS: [[u8; 33]; 33] = [
${pairs.map((row) => `    [${row.join(", ")}],`).join("\n")}
];
/// Inclusive code point ranges of Thai, Lao, Khmer and Myanmar text, which ICU breaks with
/// dictionaries.
pub(crate) static DICTIONARY_SCRIPTS: [(u32, u32); ${scripts.length}] = [
${lines(
	scripts.map(([start, end]) => `(${hex(start)}, ${hex(end)}),`),
	6
)}
];
`;
writeFileSync(join(root, "crates/game-text-index/src/line_break_tables.rs"), output);
console.log(
	`Wrote ${classes.length} class runs and ${scripts.length} dictionary script ranges from linebreak ${linebreakVersion}.`
);
