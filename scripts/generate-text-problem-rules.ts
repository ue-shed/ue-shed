/**
 * Writes the shared text-problem table (`packages/game-text/src/text-problem-rules.ts`) into the
 * native engine, so the engine and `textProblems` classify lines from one definition. Run
 * `node scripts/generate-text-problem-rules.ts` after changing the table;
 * `text-problem-rules.test.ts` fails while the Rust file is stale.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	TEXT_PROBLEMS,
	TEXT_PROBLEM_LABELS,
	TEXT_PROBLEM_RULES
} from "../packages/game-text/src/text-problem-rules.ts";

export const TEXT_PROBLEM_RULES_PATH = "crates/game-text-index/src/text_problem_rules.rs";

const quoted = (values: readonly string[]) => values.map((value) => JSON.stringify(value));
const strings = (name: string, values: readonly string[]) =>
	`pub const ${name}: [&str; ${values.length}] = [\n${quoted(values)
		.map((value) => `    ${value},\n`)
		.join("")}];\n`;
const lists = (name: string, field: "states" | "facts" | "reasons" | "signals") =>
	`pub const ${name}: [&[&str]; ${TEXT_PROBLEMS.length}] = [\n${TEXT_PROBLEMS.map(
		(problem) => `    &[${quoted(TEXT_PROBLEM_RULES[problem][field]).join(", ")}],\n`
	).join("")}];\n`;

/** The generated Rust source for the current table. */
export function renderTextProblemRules(): string {
	return [
		"//! Generated by scripts/generate-text-problem-rules.ts from\n" +
			"//! packages/game-text/src/text-problem-rules.ts. Do not edit; regenerate it instead.\n",
		"/// Every problem, worst first; bit `i` of a problem mask is `PROBLEMS[i]`.\n" +
			strings("PROBLEMS", TEXT_PROBLEMS),
		strings(
			"PROBLEM_LABELS",
			TEXT_PROBLEMS.map((problem) => TEXT_PROBLEM_LABELS[problem])
		),
		"/// Primary localization states that raise each problem, by `STATES` name.\n" +
			lists("PROBLEM_STATES", "states"),
		"/// Secondary localization facts that raise each problem, by `STATES` name.\n" +
			lists("PROBLEM_FACTS", "facts"),
		"/// Unknown reasons that raise each problem, by `REASONS` name.\n" +
			lists("PROBLEM_REASONS", "reasons"),
		"/// Facts that raise each problem, by `FACTS` name.\n" +
			lists("PROBLEM_SIGNALS", "signals"),
		"/// Whether a line with this worst problem has work before it ships.\n" +
			`pub const PROBLEM_WORK: [bool; ${TEXT_PROBLEMS.length}] = [${TEXT_PROBLEMS.map(
				(problem) => String(TEXT_PROBLEM_RULES[problem].work)
			).join(", ")}];\n`
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const root = join(dirname(fileURLToPath(import.meta.url)), "..");
	writeFileSync(join(root, TEXT_PROBLEM_RULES_PATH), renderTextProblemRules());
}
